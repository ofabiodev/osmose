package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type wrapper struct {
	Name       string
	Field      string
	Package    string
	Type       string
	ImportPath string
}

func main() {
	root, err := findRoot()
	if err == nil {
		err = generate(root)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(root string) error {
	module, err := modulePath(root)
	if err != nil {
		return err
	}
	coreFile := filepath.Join(root, "proto", "core", "core.pb.go")
	data, err := os.ReadFile(coreFile)
	if err != nil {
		return fmt.Errorf("read core protobuf: %w", err)
	}
	file, err := parser.ParseFile(token.NewFileSet(), coreFile, data, 0)
	if err != nil {
		return fmt.Errorf("parse core protobuf: %w", err)
	}

	imports := make(map[string]string)
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return fmt.Errorf("parse import path: %w", err)
		}
		name := filepath.Base(path)
		if spec.Name != nil {
			name = spec.Name.Name
		}
		imports[name] = path
	}

	wrappers := make([]wrapper, 0)
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || !strings.HasPrefix(typeSpec.Name.Name, "ClientMessage_") {
				continue
			}
			structType, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}
			for _, field := range structType.Fields.List {
				if field.Tag == nil || len(field.Names) == 0 || !isOneof(field.Tag.Value) {
					continue
				}
				star, ok := field.Type.(*ast.StarExpr)
				if !ok {
					continue
				}
				pkg, typeName, importPath, ok := innerType(star.X, module, imports)
				if !ok {
					continue
				}
				wrappers = append(wrappers, wrapper{
					Name:       typeSpec.Name.Name,
					Field:      field.Names[0].Name,
					Package:    pkg,
					Type:       typeName,
					ImportPath: importPath,
				})
			}
		}
	}
	sort.Slice(wrappers, func(i, j int) bool { return wrappers[i].Name < wrappers[j].Name })
	if len(wrappers) == 0 {
		return fmt.Errorf("no ClientMessage oneof wrappers found in %s", coreFile)
	}

	coreImport := module + "/proto/core"
	packageImports := map[string]string{"core": coreImport}
	for _, item := range wrappers {
		if item.Package != "core" {
			packageImports[item.Package] = item.ImportPath
		}
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by tools/wrapgen; DO NOT EDIT.\n\npackage rpc\n\nimport (\n\t\"fmt\"\n")
	aliases := make([]string, 0, len(packageImports))
	for alias := range packageImports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		fmt.Fprintf(&source, "\t%s %q\n", alias, packageImports[alias])
	}
	source.WriteString("\t\"google.golang.org/protobuf/proto\"\n)\n\n")
	source.WriteString("func wrap(id uint32, msg proto.Message) (*core.ClientMessage, error) {\n\tswitch value := msg.(type) {\n")
	for _, item := range wrappers {
		fmt.Fprintf(&source, "\tcase *%s.%s:\n\t\treturn &core.ClientMessage{Id: id, Message: &core.%s{%s: value}}, nil\n", item.Package, item.Type, item.Name, item.Field)
	}
	source.WriteString("\tdefault:\n\t\treturn nil, fmt.Errorf(\"%w: %T\", ErrUnsupportedRequest, msg)\n\t}\n}\n\n")
	source.WriteString("// Wrap places a typed Osmium request inside the core ClientMessage oneof.\nfunc Wrap(id uint32, msg proto.Message) (*core.ClientMessage, error) { return wrap(id, msg) }\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated wrapper: %w", err)
	}
	outFile := filepath.Join(root, "internal", "rpc", "wrap_gen.go")
	if err := os.MkdirAll(filepath.Dir(outFile), 0o755); err != nil {
		return fmt.Errorf("create wrapper directory: %w", err)
	}
	if err := os.WriteFile(outFile, formatted, 0o644); err != nil {
		return fmt.Errorf("write generated wrapper: %w", err)
	}
	return nil
}

func isOneof(rawTag string) bool {
	tag, err := strconv.Unquote(rawTag)
	if err != nil {
		return false
	}
	const prefix = `protobuf:"`
	start := strings.Index(tag, prefix)
	if start < 0 {
		return false
	}
	value := tag[start+len(prefix):]
	end := strings.IndexByte(value, '"')
	return end >= 0 && strings.Contains(value[:end], ",oneof")
}

func innerType(expr ast.Expr, module string, imports map[string]string) (string, string, string, bool) {
	switch value := expr.(type) {
	case *ast.Ident:
		return "core", value.Name, module + "/proto/core", true
	case *ast.SelectorExpr:
		pkg, ok := value.X.(*ast.Ident)
		if !ok {
			return "", "", "", false
		}
		path, ok := imports[pkg.Name]
		if !ok {
			return "", "", "", false
		}
		return pkg.Name, value.Sel.Name, path, true
	default:
		return "", "", "", false
	}
}

func findRoot() (string, error) {
	root, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			return root, nil
		}
		parent := filepath.Dir(root)
		if parent == root {
			return "", fmt.Errorf("go.mod not found")
		}
		root = parent
	}
}

func modulePath(root string) (string, error) {
	data, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", fmt.Errorf("read go.mod: %w", err)
	}
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 2 && fields[0] == "module" {
			return fields[1], nil
		}
	}
	return "", fmt.Errorf("module directive missing from %s", filepath.Join(root, "go.mod"))
}
